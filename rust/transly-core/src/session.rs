//! `session.ts`: покласти результат мережевого обміну (синхронізації) у застосунок.
//!
//! Обмін почався з проєкту, яким він був до запиту, а перекладач міг друкувати, поки він ішов. Взяти результат як є — загубити ті
//! правки (вони живуть в об'єкті, що замінюється). Тому результат зливається з проєктом, яким він є зараз: злиття лишає новішу
//! версію кожного рядка, тож правки, набрані під час запиту, виграють у синхронізованого до них, а надіслане іншими пристроями лишається.
//! Скидання, зроблене під час запиту, теж виграє.

use crate::project::{merge_projects, SavedProject};

/// `same` — це той самий об'єкт у пам'яті (у TS порівнюється посилання); тоді злиття не потрібне.
pub fn adopt_synced(live: &SavedProject, synced: &SavedProject, same: bool) -> SavedProject {
    if same {
        synced.clone()
    } else {
        merge_projects(live, synced, 0).project
    }
}
